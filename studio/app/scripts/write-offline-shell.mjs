import { createHash } from "node:crypto";
import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const dist = new URL("../dist/", import.meta.url);
const assetsDir = new URL("assets/", dist);
const entries = await readdir(assetsDir, { withFileTypes: true });
const assetNames = entries.filter((entry) => entry.isFile()).map((entry) => entry.name).sort();

const assets = [];
for (const name of assetNames) {
  const path = join(fileURLToPath(assetsDir), name);
  const size = (await stat(path)).size;
  assets.push({ url: `/assets/${name}`, size });
}

const fingerprint = createHash("sha256")
  .update(JSON.stringify(assets))
  .digest("hex")
  .slice(0, 16);
const cacheName = `quillframe-studio-shell-${fingerprint}`;
const precache = [
  "/index.html",
  "/manifest.webmanifest",
  "/quillframe-mark.svg",
  ...assets.map((asset) => asset.url),
];

const source = `/* generated by scripts/write-offline-shell.mjs */
const CACHE_NAME=${JSON.stringify(cacheName)};
const PRECACHE=${JSON.stringify(precache)};
const API_PREFIX="/api/";

self.addEventListener("install",(event)=>{
  event.waitUntil(caches.open(CACHE_NAME).then((cache)=>cache.addAll(PRECACHE)).then(()=>self.skipWaiting()));
});

self.addEventListener("activate",(event)=>{
  event.waitUntil(caches.keys().then((keys)=>Promise.all(keys.filter((key)=>key.startsWith("quillframe-studio-shell-")&&key!==CACHE_NAME).map((key)=>caches.delete(key)))).then(()=>self.clients.claim()));
});

self.addEventListener("fetch",(event)=>{
  const request=event.request;
  if(request.method!=="GET") return;
  const url=new URL(request.url);
  if(url.origin!==self.location.origin||url.pathname.startsWith(API_PREFIX)) return;

  if(request.mode==="navigate"){
    event.respondWith(fetch(request).catch(()=>caches.match("/index.html",{ignoreVary:true})));
    return;
  }

  if(url.pathname.startsWith("/assets/")||PRECACHE.includes(url.pathname)){
    event.respondWith(caches.match(url.pathname,{ignoreVary:true}).then((cached)=>cached||fetch(request)));
  }
});
`;

if (source.includes('PRECACHE=["/api/')) throw new Error("API route entered precache");
if (!source.includes('url.pathname.startsWith(API_PREFIX)')) throw new Error("API exclusion missing");
if (Buffer.byteLength(source) > 8 * 1024) throw new Error("generated service worker exceeds 8 KiB budget");

await writeFile(new URL("sw.js", dist), source, "utf8");
console.log(JSON.stringify({
  schema: "quillframe_studio_offline_shell_v1",
  cache: cacheName,
  precache_entries: precache.length,
  service_worker_bytes: Buffer.byteLength(source),
  api_cached: false,
  navigation_strategy: "network_first_offline_shell_fallback",
}));
